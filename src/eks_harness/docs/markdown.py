from __future__ import annotations

import json
import re
from collections.abc import Iterable, Mapping, Sequence
from typing import Any

from pydantic import BaseModel

GENERATED_NOTE = "Generated by `eks-harness docs` from the built-in registry. Do not edit by hand; run `eks-harness docs --out docs/reference` instead."
REF_DEFS = frozenset({"RefExpr", "ItemExpr", "FmtExpr"})
DEF_ALIASES = {"JsonValue": "JSON"}
FORMAT_NAMES = {"eks-time": "Time", "eks-color": "Color"}
JSON_TYPES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None", "object": "dict"}
WHITESPACE = re.compile(r"\s+")
QUALIFIED_PREFIX = "eks_harness__"
GENERIC_DEF = re.compile(r"(?P<base>[A-Z][A-Za-z0-9]*)_(?P<arg>.+)_")
GENERIC_ARGS = {
    "float": "float",
    "int": "int",
    "JsonValue": "JSON",
    "tuple_float__float__float_": "tuple[float, float, float]",
    "Annotated_str__AfterValidator__WithJsonSchema_": "Color",
}


def cell(value: object) -> str:
    text = "" if value is None else str(value)
    return WHITESPACE.sub(" ", text).strip().replace("|", "\\|")


def sentence(text: str) -> str:
    value = cell(text).rstrip(".")
    if not value:
        return ""
    return value[0].upper() + value[1:] + "."


def code(value: object) -> str:
    text = cell(value)
    if not text:
        return ""
    fence = "``" if "`" in text else "`"
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def table(headers: Sequence[str], rows: Iterable[Sequence[object]]) -> str:
    lines = ["| " + " | ".join(cell(header) for header in headers) + " |",
             "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        values = [str(value) if value is not None else "" for value in row]
        if len(values) != len(headers):
            raise ValueError(f"table row has {len(values)} cells, expected {len(headers)}: {values!r}")
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines)


def json_block(value: Any) -> str:
    return "```json\n" + json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n```"


def anchor(text: str) -> str:
    lowered = text.strip().lower()
    kept = re.sub(r"[^\w\- ]", "", lowered)
    return kept.replace(" ", "-")


def def_name(reference: str) -> str:
    name = reference.rsplit("/", 1)[-1]
    if name.startswith(QUALIFIED_PREFIX):
        return ".".join(name.split("__")[-2:])
    generic = GENERIC_DEF.fullmatch(name)
    if generic is not None:
        argument = generic.group("arg")
        return f"{generic.group('base')}[{GENERIC_ARGS.get(argument, argument)}]"
    return DEF_ALIASES.get(name, name)


def type_text(schema: Any) -> str:
    if not isinstance(schema, Mapping) or not schema:
        return "any"
    if "$ref" in schema:
        name = def_name(str(schema["$ref"]))
        return "Ref" if name in REF_DEFS else name
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(type_text(option) for option in schema[key]))
    fmt = schema.get("format")
    if isinstance(fmt, str) and fmt in FORMAT_NAMES:
        return FORMAT_NAMES[fmt]
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(type_text({**schema, "type": item}) for item in kind)
    if kind == "array":
        prefix = schema.get("prefixItems")
        if isinstance(prefix, list):
            return "tuple[" + ", ".join(type_text(item) for item in prefix) + "]"
        return f"list[{type_text(schema.get('items'))}]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, Mapping):
            return f"dict[str, {type_text(extra)}]"
        return "dict"
    if isinstance(kind, str):
        return JSON_TYPES.get(kind, kind)
    return "any"


def default_text(field: Mapping[str, Any]) -> str:
    if "default" not in field:
        return ""
    return json.dumps(field["default"], ensure_ascii=False, sort_keys=True)


def field_rows(schema: Mapping[str, Any]) -> list[tuple[str, str, str, str, str]]:
    properties: Mapping[str, Any] = schema.get("properties", {})
    required = set(schema.get("required", []))
    rows: list[tuple[str, str, str, str, str]] = []
    for name, field in properties.items():
        needed = name in required
        rows.append((
            code(name),
            code(type_text(field)),
            "yes" if needed else "",
            "" if needed else code(default_text(field)),
            cell(field.get("description", "") if isinstance(field, Mapping) else ""),
        ))
    return rows


def field_table(schema: Mapping[str, Any], name: str = "Argument", empty: str = "No arguments.") -> str:
    rows = field_rows(schema)
    if not rows:
        return empty
    return table([name, "Type", "Required", "Default", "Description"], rows)


def model_schema(model: type[BaseModel]) -> dict[str, Any]:
    return model.model_json_schema(by_alias=True, mode="validation")


def model_field_table(model: type[BaseModel], headers: Sequence[str] = ("Field", "Type", "Default", "Description")) -> str:
    schema = model_schema(model)
    properties: Mapping[str, Any] = schema.get("properties", {})
    required = set(schema.get("required", []))
    rows = [
        (code(name), code(type_text(field)), "required" if name in required else code(default_text(field)),
         cell(field.get("description", "")))
        for name, field in properties.items()
    ]
    if not rows:
        return "No fields."
    return table(headers, rows)


def page(title: str, *blocks: str) -> str:
    parts = [f"# {title}", GENERATED_NOTE, *(block.strip("\n") for block in blocks if block.strip())]
    return "\n\n".join(parts) + "\n"


